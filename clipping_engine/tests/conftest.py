def wait_for(predicate, timeout, interval=0.25):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if predicate():
            return True
        time.sleep(interval)
    return predicate()


class MockDiscord:
    """Local stand-in for a Discord webhook: records multipart/JSON posts, can answer 429/500."""

    def __init__(self):
        import email.parser
        import email.policy
        import json as _json
        from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

        self.requests = []
        self.script = []          # status codes to answer first, e.g. [429, 200]
        outer = self

        class Handler(BaseHTTPRequestHandler):
            def do_POST(self):
                body = self.rfile.read(int(self.headers.get("Content-Length") or 0))
                ctype = self.headers.get("Content-Type", "")
                record = {"path": self.path, "content_type": ctype, "files": {}, "payload": None}
                if ctype.startswith("multipart/form-data"):
                    msg = email.parser.BytesParser(policy=email.policy.HTTP).parsebytes(
                        b"Content-Type: " + ctype.encode() + b"\r\n\r\n" + body)
                    for part in msg.iter_parts():
                        name = part.get_param("name", header="content-disposition")
                        data = part.get_payload(decode=True)
                        if name == "payload_json":
                            record["payload"] = _json.loads(data)
                        else:
                            record["files"][name] = (part.get_filename(), len(data))
                else:
                    record["payload"] = _json.loads(body or b"{}")
                outer.requests.append(record)
                status = outer.script.pop(0) if outer.script else 200
                self.send_response(status)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                if status == 429:
                    self.wfile.write(b'{"message": "You are being rate limited.", "retry_after": 0.2, "global": false}')
                else:
                    self.wfile.write(b'{"id": "1"}')

            def log_message(self, *args):
                pass

        self.httpd = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        threading.Thread(target=self.httpd.serve_forever, daemon=True).start()
        self.url = f"http://127.0.0.1:{self.httpd.server_address[1]}/api/webhooks/123/SECRET-TOKEN"

    def close(self):
        self.httpd.shutdown()


