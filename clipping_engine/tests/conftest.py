def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


class _QuietHandler(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args):
        pass


class _Server(socketserver.ThreadingMixIn, socketserver.TCPServer):
    allow_reuse_address = True
    daemon_threads = True


class LiveHLS:
    """A live HLS stream generated in real time by FFmpeg and served over HTTP."""

    def __init__(self, folder, port):
        self.folder = Path(folder)
        self.port = port
        self.gen = None
        self.httpd = None

    @property
    def url(self):
        return f"hls://http://127.0.0.1:{self.port}/live.m3u8"

    def start(self):
        self.folder.mkdir(parents=True, exist_ok=True)
        for f in self.folder.glob("*"):
            f.unlink()
        self.gen = subprocess.Popen([
            "ffmpeg", "-hide_banner", "-loglevel", "error", "-re",
            "-f", "lavfi", "-i", "testsrc2=size=320x180:rate=30",
            "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=48000",
            "-c:v", "libx264", "-preset", "ultrafast", "-g", "30", "-c:a", "aac",
            "-f", "hls", "-hls_time", "1", "-hls_list_size", "6", "-hls_flags", "delete_segments",
            str(self.folder / "live.m3u8"),
        ])
        handler = functools.partial(_QuietHandler, directory=str(self.folder))
        self.httpd = _Server(("127.0.0.1", self.port), handler)
        threading.Thread(target=self.httpd.serve_forever, daemon=True).start()
        deadline = time.time() + 15
        while not (self.folder / "live.m3u8").exists():
            if time.time() > deadline:
                raise RuntimeError("HLS generator did not start")
            time.sleep(0.2)
        time.sleep(2)   # a few HLS segments

    def stop(self):
        if self.httpd:
            self.httpd.shutdown()
            self.httpd.server_close()
            self.httpd = None
        if self.gen:
            self.gen.terminate()
            self.gen.wait(10)
            self.gen = None


