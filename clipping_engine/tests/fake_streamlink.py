#!/usr/bin/env python3
"""
Stand-in for the streamlink CLI, used by test_recording.py.

Writes a live MPEG-TS stream (generated by FFmpeg in real time) to stdout,
and can imitate a Twitch ad break exactly like Streamlink does: log
"Filtering out segments and pausing stream output", drop the stream data
for a while, then log "Resuming stream output" and continue.

Environment:
  FAKE_PAUSE_AT       seconds after start to begin the pause (default: never)
  FAKE_PAUSE_SECONDS  length of the pause
  FAKE_PAUSE_SILENT   "1" = pause WITHOUT the ad-filter log lines (a real stall)
"""

import os
import subprocess
import sys
import time

args = sys.argv[1:]
if "--version" in args:
    print("streamlink 8.6.3 (fake)")
    sys.exit(0)
if "--can-handle-url" in args:
    sys.exit(0)

pause_at = float(os.getenv("FAKE_PAUSE_AT", "1e9"))
pause_len = float(os.getenv("FAKE_PAUSE_SECONDS", "0"))
silent = os.getenv("FAKE_PAUSE_SILENT") == "1"

gen = subprocess.Popen(
    ["ffmpeg", "-hide_banner", "-loglevel", "error", "-re", "-f", "lavfi", "-i", "testsrc2=size=320x180:rate=30",
     "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=48000", "-c:v", "libx264", "-preset", "ultrafast",
     "-g", "30", "-c:a", "aac", "-f", "mpegts", "-"],
    stdout=subprocess.PIPE)
print("[cli][info] Opening stream: 1080p60 (hls)", file=sys.stderr, flush=True)
start = time.monotonic()
paused = False
out = sys.stdout.buffer
try:
    while True:
        chunk = gen.stdout.read(4096)
        if not chunk:
            break
        elapsed = time.monotonic() - start
        in_pause = pause_at <= elapsed < pause_at + pause_len
        if in_pause and not paused:
            paused = True
            if not silent:
                print("[stream.hls][info] Filtering out segments and pausing stream output", file=sys.stderr, flush=True)
        if paused and not in_pause:
            paused = False
            if not silent:
                print("[stream.hls][info] Resuming stream output", file=sys.stderr, flush=True)
        if not paused:
            out.write(chunk)
            out.flush()
except (BrokenPipeError, KeyboardInterrupt):
    pass
finally:
    gen.terminate()
